export function createNewSection(type: SectionType): WebsiteSection {
  const blueprint = SECTION_BLUEPRINTS[type];
  return {
    id: `sec-${Date.now()}-${Math.random().toString(36).substr(2, 4)}`,
    type,
    layoutVariant: blueprint.layoutVariant || 'split',
    title: blueprint.title || 'New Section',
    subtitle: blueprint.subtitle || '',
    badge: blueprint.badge || '',
    description: blueprint.description || '',
    primaryBtn: blueprint.primaryBtn ? { ...blueprint.primaryBtn } : undefined,
    secondaryBtn: blueprint.secondaryBtn ? { ...blueprint.secondaryBtn } : undefined,
    image: blueprint.image,
    imageAlt: blueprint.imageAlt || 'Section illustration',
    bgVariant: 'default',
    paddingY: blueprint.paddingY || 'normal',
    textAlign: blueprint.textAlign || 'left',
    items: blueprint.items ? blueprint.items.map(it => ({ ...it, id: `item-${Date.now()}-${Math.random().toString(36).substr(2, 4)}` })) : [],
  };
}
